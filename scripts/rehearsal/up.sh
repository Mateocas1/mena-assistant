#!/usr/bin/env bash
# Brings up the whole Mena local rehearsal in one command:
#
#   mena-nails API + PostgreSQL + seed   →  http://127.0.0.1:8080
#   mena-nails web (Vite dev)            →  http://localhost:5173
#   mena-assistant bot (Telegram)        →  long polling, stock on http
#
# It removes the three first-run pitfalls that make the manual README run fail:
#   1. owner credentials are generated and exported before the API starts
#      (otherwise /auth/login answers 503 and the page cannot sign in);
#   2. the API's allowed origin and the origin the browser opens are the same
#      string (localhost:5173), so CORS does not reject the page;
#   3. the `seed` profile always runs, so the catalog and stocktake have items.
#
# Usage: scripts/rehearsal/up.sh [--turnos=http|mock] [--no-bot]
# Secrets land in ~/.config/mena/rehearsal.env (mode 600, never committed).
set -euo pipefail

# shellcheck source=./lib.sh
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib.sh"

TURNOS_OVERRIDE=""
START_BOT=1
for arg in "$@"; do
  case "$arg" in
    --turnos=*) TURNOS_OVERRIDE="${arg#--turnos=}" ;;
    --no-bot) START_BOT=0 ;;
    -h | --help)
      sed -n '2,20p' "${BASH_SOURCE[0]}"
      exit 0
      ;;
    *) die "unknown argument: $arg" ;;
  esac
done

run_bcrypt() {
  local password="$1"
  if python3 -c 'import bcrypt' >/dev/null 2>&1; then
    python3 -c \
      'import bcrypt,sys; print(bcrypt.hashpw(sys.argv[1].encode(), bcrypt.gensalt()).decode())' \
      "$password"
    return 0
  fi
  if docker image inspect httpd:alpine >/dev/null 2>&1; then
    docker run --rm httpd:alpine htpasswd -bnBC 12 '' "$password" | tr -d ':\n'
    return 0
  fi
  die "need python3 with the bcrypt module (or the httpd:alpine image) to hash the owner password"
}

ensure_secret_file() {
  [ -f "$REHEARSAL_ENV" ] && return 0
  require_cmd openssl
  log "generating $REHEARSAL_ENV (mode 600, local rehearsal only)"
  mkdir -p "$(dirname "$REHEARSAL_ENV")"
  local words password hash session service_token digest assistant_token
  words=(luna rosa perla coral jade topacio ambar nieve)
  password="mena-${words[$((RANDOM % ${#words[@]}))]}-$((RANDOM % 9000 + 1000))"
  hash="$(run_bcrypt "$password")"
  session="$(openssl rand -base64 48 | tr -d '\n')"
  service_token="svc_rehearsal_$(openssl rand -hex 16)"
  digest="$(printf '%s' "$service_token" | sha256sum | awk '{print $1}')"
  assistant_token="$(openssl rand -hex 32)"

  umask 077
  {
    printf '# Generated by scripts/rehearsal/up.sh — local rehearsal secrets.\n'
    printf '# Mode 600, never committed, never printed. Delete to regenerate.\n'
    printf "REHEARSAL_OWNER_PASSWORD='%s'\n" "$password"
    printf "OWNER_PASSWORD_BCRYPT_HASH='%s'\n" "$hash"
    printf "OWNER_SESSION_SECRET='%s'\n" "$session"
    printf "MENA_NAILS_SERVICE_TOKEN='%s'\n" "$service_token"
    printf "API_SERVICE_TOKENS='assistant:%s'\n" "$digest"
    printf "ASSISTANT_TOKEN='%s'\n" "$assistant_token"
  } >"$REHEARSAL_ENV"
  chmod 600 "$REHEARSAL_ENV"
}

main() {
  require_cmd docker
  require_cmd curl
  require_cmd node
  prepare_docker_config
  docker info >/dev/null 2>&1 || die "the Docker daemon is not reachable"
  [ -f "$COMPOSE_FILE" ] || die "mena-nails compose not found at $COMPOSE_FILE (set MENA_NAILS_PATH)"
  [ -d "$WEB_DIR/node_modules" ] || die "run (cd $WEB_DIR && npm ci) once before the rehearsal"
  mkdir -p "$STATE_DIR"

  ensure_secret_file
  load_env_file "$REHEARSAL_ENV"
  load_telegram_env || warn "no Telegram credentials in $TELEGRAM_ENV — the bot will be skipped"

  # ── the stack (API_ALLOWED_ORIGIN is exported by lib.sh) ────────────────────
  local api_running=0
  if compose ps --status running --services 2>/dev/null | grep -qx api; then
    api_running=1
    log "mena-nails API already running in project $PROJECT"
  else
    for port in "$API_PORT" "$WEB_PORT"; do
      port_free "$port" || die "port $port is busy; stop whatever uses it (or set MENA_REHEARSAL_*_PORT)"
    done
    log "starting mena-nails (project $PROJECT) with the seed profile…"
    compose_seed up -d --build
  fi

  log "waiting for $API_ORIGIN/readyz…"
  wait_for_code "$API_ORIGIN/readyz" 200 240 ||
    die "the API never became ready (docker compose -p $PROJECT logs api)"

  # ── pitfall 1: owner credentials ───────────────────────────────────────────
  local login_code
  login_code="$(
    jq -n --arg p "$REHEARSAL_OWNER_PASSWORD" '{password: $p}' |
      curl -s -o /dev/null -w '%{http_code}' --max-time 10 \
        -H "Origin: $WEB_ORIGIN" -H 'Content-Type: application/json' \
        --data-binary @- "$API_ORIGIN/auth/login"
  )"
  case "$login_code" in
    200) log "owner login OK ($WEB_ORIGIN)" ;;
    503)
      die "owner login answered 503: the API started without OWNER_PASSWORD_BCRYPT_HASH /
OWNER_SESSION_SECRET. Recreate the stack: scripts/rehearsal/down.sh && scripts/rehearsal/up.sh"
      ;;
    403)
      die "owner login answered 403: the browser origin ($WEB_ORIGIN) is not API_ALLOWED_ORIGIN.
Open the app at exactly $WEB_ORIGIN"
      ;;
    *) die "owner login answered HTTP $login_code (expected 200)" ;;
  esac

  # ── pitfall 3: seeded catalog reachable with the service credential ────────
  local catalog_body catalog_code catalog_count
  catalog_body="$(
    curl -s --max-time 10 -H "Authorization: Bearer $MENA_NAILS_SERVICE_TOKEN" \
      -w '\n%{http_code}' "$API_ORIGIN/catalog/items" || true
  )"
  catalog_code="$(printf '%s' "$catalog_body" | tail -n1)"
  case "$catalog_code" in
    200)
      catalog_count="$(printf '%s' "$catalog_body" | sed '$d' | jq 'length' 2>/dev/null || echo '?')"
      if [ "$catalog_count" = "0" ]; then
        die "the catalog is empty: the seed did not run (docker compose -p $PROJECT --profile seed run --rm seed)"
      fi
      log "seeded catalog reachable with the service credential: $catalog_count items"
      ;;
    401) die "the service credential was rejected (401): API_SERVICE_TOKENS does not match MENA_NAILS_TOKEN" ;;
    403) die "the service credential cannot read /catalog/items (403): mena-nails predates PR #158" ;;
    *) die "GET /catalog/items answered HTTP $catalog_code" ;;
  esac

  # ── the web PWA ────────────────────────────────────────────────────────────
  if pid_alive "$WEB_PID_FILE"; then
    log "web dev server already running (pid $(cat "$WEB_PID_FILE"))"
  else
    log "starting the web dev server on $WEB_ORIGIN with VITE_PUBLIC_API_ORIGIN=$VITE_PUBLIC_API_ORIGIN"
    (cd "$WEB_DIR" && start_bg "$WEB_PID_FILE" "$WEB_LOG" npm run dev -- --host "$WEB_HOST" --port "$WEB_PORT")
  fi
  wait_for_code "$WEB_ORIGIN/" 200 120 || die "the web dev server did not answer on $WEB_ORIGIN (log: $WEB_LOG)"

  # ── the bot ────────────────────────────────────────────────────────────────
  local turnos="${TURNOS_OVERRIDE:-${TURNOS_BACKEND:-mock}}"
  if [ "$START_BOT" = "1" ] && [ -n "${TELEGRAM_BOT_TOKEN:-}" ]; then
    export TELEGRAM_BOT_TOKEN TELEGRAM_ALLOWLIST
    if [ -z "${LLM_API_KEY:-}" ]; then
      LLM_API_KEY="$(jq -r '.nan.key // empty' "$AUTH_JSON" 2>/dev/null || true)"
    fi
    if [ -z "${LLM_API_KEY:-}" ]; then
      warn "no LLM_API_KEY and no .nan.key in $AUTH_JSON — skipping the bot"
    else
      export LLM_API_KEY
      export LLM_BASE_URL="${LLM_BASE_URL:-https://api.nan.builders/v1}"
      export FEATURE_STOCK=true
      export STOCK_BACKEND=http
      export MENA_NAILS_API_URL="$API_ORIGIN"
      export MENA_NAILS_TOKEN="$MENA_NAILS_SERVICE_TOKEN"
      export STOCK_ALERT_ENABLED=false
      export TURNOS_BACKEND="$turnos"
      export HEALTH_FILE="$STATE_DIR/bot-alive"
      export AUDIT_LOG_FILE="$STATE_DIR/audit.log"

      if [ "$turnos" = "http" ]; then
        [ -n "${ASSISTANT_API_BASE_URL:-}" ] && [ -n "${ASSISTANT_TOKEN:-}" ] ||
          die "TURNOS_BACKEND=http needs ASSISTANT_API_BASE_URL and ASSISTANT_TOKEN (a test-kimi dev deployment)"
        export ASSISTANT_API_BASE_URL ASSISTANT_TOKEN
      else
        warn "TURNOS_BACKEND=mock: the bot answers from in-memory fixtures. See docs/rehearsal.md for the Convex dev deployment gap"
      fi

      log "starting the bot (TURNOS_BACKEND=$turnos, FEATURE_STOCK=true, STOCK_BACKEND=http)…"
      (cd "$REPO_ROOT" && start_bg "$BOT_PID_FILE" "$BOT_LOG" pnpm exec tsx src/index.ts)

      local username
      username="$(
        printf 'url = "https://api.telegram.org/bot%s/getMe"\n' "$TELEGRAM_BOT_TOKEN" |
          curl -s --max-time 15 -K - | jq -r 'if .ok then .result.username else ("error:" + (.description // "unknown")) end'
      )"
      log "Telegram getMe: $username"
      sleep 3
      pid_alive "$BOT_PID_FILE" || die "the bot exited right after start (log: $BOT_LOG)"
      log "bot pid $(cat "$BOT_PID_FILE"), log $BOT_LOG"
    fi
  elif [ "$START_BOT" = "1" ]; then
    warn "no TELEGRAM_BOT_TOKEN — the bot was not started"
  fi

  {
    printf 'PROJECT=%s\nMENA_NAILS_PATH=%s\nAPI_ORIGIN=%s\nWEB_ORIGIN=%s\nTURNOS_BACKEND=%s\n' \
      "$PROJECT" "$MENA_NAILS_PATH" "$API_ORIGIN" "$WEB_ORIGIN" "$turnos"
  } >"$STATE_FILE"

  log "ready. Open $WEB_ORIGIN (owner password is in $REHEARSAL_ENV)."
  log "check with scripts/rehearsal/status.sh · stop with scripts/rehearsal/down.sh"
}

main "$@"
